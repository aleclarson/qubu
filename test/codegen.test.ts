test("rejects generated key proofs that TypeScript cannot satisfy", () => {
  const cases = [
    ["nullable-unique-target", "does not target an exact"],
    ["unequal-arity", "unequal local and target arity"],
    ["unmatched-target", "does not target an exact"],
    ["nullable-primary", "contains nullable columns"],
  ] as const

  for (const [kind, message] of cases) {
    const result = generateSchemaSource(invalidProofInput(kind))

    expect(result.ok).toBe(false)
    expect(result).not.toHaveProperty("source")
    if (!result.ok) {
      expect(result.diagnostics).toEqual(
        expect.arrayContaining([
          expect.objectContaining({
            code: "unrepresentable-fact",
            message: expect.stringContaining(message),
          }),
        ]),
      )
    }
  }
})

