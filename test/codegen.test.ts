function physicalFacts(snapshot: SchemaSnapshot): unknown {
  const tablesById = new Map(snapshot.tables.map((table) => [table.id, table]))
  const columnsByTable = new Map(
    snapshot.tables.map((table) => [
      table.id,
      new Map(table.columns.map((column) => [column.id, column.physicalName])),
    ]),
  )

  return {
    dialect: snapshot.dialect,
    namespace: snapshot.namespace,
    tables: [...snapshot.tables].sort(comparePhysical).map((table) => ({
      physicalName: table.physicalName,
      columns: [...table.columns].sort(comparePhysical).map((column) => {
        const { id: _id, ...facts } = column

        void _id
        return facts
      }),
      constraints: [...table.constraints]
        .sort(comparePhysical)
        .map((constraint) => physicalConstraint(constraint, table.id, tablesById, columnsByTable)),
      indexes: [...table.indexes].sort(comparePhysical).map((index) => {
        const { id: _id, ...facts } = index

        void _id
        const columns = columnsByTable.get(table.id)

        return {
          ...facts,
          terms: index.terms.map((term) => physicalIndexTerm(term, columns)),
          includedColumns: index.includedColumns?.map(
            (column) => columns?.get(column) ?? `missing:${column}`,
          ),
        }
      }),
    })),
  }
}

function physicalConstraint(
  constraint: SnapshotConstraint,
  tableId: string,
  tables: ReadonlyMap<string, SchemaSnapshot["tables"][number]>,
  columns: ReadonlyMap<string, ReadonlyMap<string, string>>,
): unknown {
  const { id: _id, ...facts } = constraint

  void _id
  if (constraint.kind === "check") {
    return facts
  }

  const local = constraint.columns.map(
    (column) => columns.get(tableId)?.get(column) ?? `missing:${column}`,
  )

  if (constraint.kind !== "foreign-key") {
    return {
      ...facts,
      columns: local,
    }
  }

  return {
    ...facts,
    columns: local,
    target: {
      table:
        tables.get(constraint.target.table)?.physicalName ?? `missing:${constraint.target.table}`,
      columns: constraint.target.columns.map(
        (column) => columns.get(constraint.target.table)?.get(column) ?? `missing:${column}`,
      ),
    },
  }
}

function physicalIndexTerm(
  term: SnapshotIndexTerm,
  columns: ReadonlyMap<string, string> | undefined,
): unknown {
  if (term.kind === "column") {
    return {
      ...term,
      column: columns?.get(term.column) ?? `missing:${term.column}`,
    }
  }

  if (term.kind === "expression") {
    return term
  }

  return {
    ...term,
    expression:
      term.expression.kind === "column"
        ? {
            ...term.expression,
            column: columns?.get(term.expression.column) ?? `missing:${term.expression.column}`,
          }
        : term.expression,
  }
}

function comparePhysical(
  left: { readonly physicalName: string },
  right: { readonly physicalName: string },
): number {
  return left.physicalName.localeCompare(right.physicalName)
}

function nativeTypeInput(
  dialect: CatalogDialect,
  declaration: string,
  tablePhysicalName = "records",
  facts: Partial<CatalogColumn> = {},
): IntrospectionSuccess {
  const namespace = dialect === "sqlite" ? "main" : "app_data"
  const catalog: IntrospectionCatalog = {
    dialect,
    server: {
      ...codegenCatalog.server,
      product: dialect === "postgresql" ? "PostgreSQL" : dialect === "mysql" ? "MySQL" : "SQLite",
    },
    namespace: {
      kind:
        dialect === "postgresql"
          ? "postgres-schema"
          : dialect === "mysql"
            ? "mysql-database"
            : "sqlite-database",
      name: namespace,
    },
    tables: [
      {
        kind: "table",
        id: tablePhysicalName,
        identitySource: "physical-name",
        physicalName: tablePhysicalName,
        columns: [
          {
            kind: "column",
            id: "value",
            identitySource: "physical-name",
            physicalName: "value",
            ordinalPosition: 1,
            nullable: false,
            storage: { nativeType: declaration },
            ...facts,
          },
        ],
        constraints: [],
        indexes: [],
      },
    ],
    deferredObjects: [],
    diagnostics: [],
  }
  const result = mapCatalogToSnapshot(catalog, { namespace })

  if (!result.ok) {
    throw new Error(result.diagnostics.map((issue) => issue.message).join("\n"))
  }

  return result
}

function invalidProofInput(
  kind: "nullable-unique-target" | "unequal-arity" | "unmatched-target" | "nullable-primary",
): IntrospectionSuccess {
  const targetColumns =
    kind === "unequal-arity"
      ? [proofColumn("part_a"), proofColumn("part_b")]
      : kind === "unmatched-target"
        ? [proofColumn("id"), proofColumn("code")]
        : [proofColumn("id", true)]
  const keyColumns = kind === "unequal-arity" ? ["part_a", "part_b"] : ["id"]
  const targetKey: CatalogConstraint =
    kind === "nullable-unique-target"
      ? {
          kind: "unique",
          id: "parent_records_key",
          identitySource: "physical-name",
          physicalName: "parent_records_key",
          columns: keyColumns,
          nulls: "distinct",
        }
      : {
          kind: "primary-key",
          id: "parent_records_key",
          identitySource: "physical-name",
          physicalName: "parent_records_key",
          columns: keyColumns,
        }
  const parent = {
    kind: "table" as const,
    id: "parent_records",
    identitySource: "physical-name" as const,
    physicalName: "parent_records",
    columns: targetColumns,
    constraints: [targetKey],
    indexes: [],
  }
  const tables: IntrospectionCatalog["tables"] =
    kind === "nullable-primary"
      ? [parent]
      : [
          parent,
          {
            kind: "table",
            id: "child_records",
            identitySource: "physical-name",
            physicalName: "child_records",
            columns: [proofColumn("parent_id")],
            constraints: [
              {
                kind: "foreign-key",
                id: "child_records_parent_fk",
                identitySource: "physical-name",
                physicalName: "child_records_parent_fk",
                columns: ["parent_id"],
                target: {
                  table: "parent_records",
                  columns:
                    kind === "unequal-arity"
                      ? ["part_a", "part_b"]
                      : kind === "unmatched-target"
                        ? ["code"]
                        : ["id"],
                },
              },
            ],
            indexes: [],
          },
        ]
  const catalog: IntrospectionCatalog = {
    ...codegenCatalog,
    namespace: {
      kind: "postgres-schema",
      name: "proof_data",
    },
    tables,
    deferredObjects: [],
    diagnostics: [],
  }
  const result = mapCatalogToSnapshot(catalog, { namespace: "proof_data" })

  if (!result.ok) {
    throw new Error(result.diagnostics.map((issue) => issue.message).join("\n"))
  }

  return result
}

function proofColumn(physicalName: string, nullable = false): CatalogColumn {
  return {
    kind: "column",
    id: physicalName,
    identitySource: "physical-name",
    physicalName,
    ordinalPosition: 1,
    nullable,
    storage: { nativeType: "integer" },
  }
}
