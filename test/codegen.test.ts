test("generates deterministic escaped source for complete Snapshot v1 facts", () => {
  const first = generateSchemaSource(codegenInput)
  const second = generateSchemaSource(codegenInput)

  expect(first).toEqual(second)
  expect(first.ok).toBe(true)
  if (!first.ok) {
    return
  }

  expect(first.source).toContain("export const accountEntries: _AccountEntriesTable = _qubu.table(")
  expect(first.source).toContain("export const parentRecords: _ParentRecordsTable = _qubu.table(")
  expect(first.source).toContain("export const appDataSchema = _qubu.schema(")
  expect(first.source).toContain("_qubu.catalogCheck(")
  expect(first.source).toContain("_qubu.catalogForeignKey(")
  expect(first.source).toContain(
    '() => _qubu.references(parentRecords, parentRecords.columns["id"])',
  )
  expect(first.source).toContain("generatedColumn: _qubu.generatedColumn(")
  expect(first.source).toContain('include: [_current.columns["status"]]')
  expect(first.source).toContain("where: _catalogPredicate(")
  expect(first.source).not.toContain("\nexport const hacked = true")
  expect(first.source.match(/Generated by Qubu/g)).toHaveLength(1)
  expect(first.source).not.toMatch(/\sas\s+(?:const|unknown|[A-Z])/)
  expect(first.diagnostics).toEqual(
    expect.arrayContaining([
      expect.objectContaining({ code: "unmodeled-object" }),
      expect.objectContaining({
        code: "excluded-object-family",
        path: ["catalog", "deferredObjects"],
      }),
    ]),
  )
})

test("applies controlled naming and column type mappings", () => {
  const result = generateSchemaSource(codegenInput, {
    naming(context) {
      if (context.kind === "schema") {
        return "applicationSchema"
      }

      if (context.kind === "column" && context.physicalName === "parent_id") {
        return "ownerId"
      }
    },
    mapColumn(context) {
      if (context.columnPhysicalName === "status") {
        return {
          output: "string",
          insert: "string",
          update: "string",
          sqlDomain: "text",
        }
      }
    },
  })

  expect(result.ok).toBe(true)
  if (!result.ok) {
    return
  }

  expect(result.source).toContain("export const applicationSchema")
  expect(result.source).toContain('"ownerId": _catalogColumn<')
  expect(result.source).toContain(
    '"status": _catalogColumn<string, string, string, _qubu.SqlText>()',
  )
})

test("infers SQL domains only from exact native declarations", () => {
  const cases = [
    ["postgresql", "integer", "_qubu.SqlInteger"],
    ["postgresql", "int4", "_qubu.SqlUnknown"],
    ["postgresql", "numeric(10, 2)", "_qubu.SqlUnknown"],
    ["mysql", "int", "_qubu.SqlInteger"],
    ["mysql", "integer", "_qubu.SqlUnknown"],
    ["sqlite", "INTEGER", "_qubu.SqlUnknown"],
  ] as const

  for (const [dialect, declaration, sqlDomain] of cases) {
    const result = generateSchemaSource(nativeTypeInput(dialect, declaration))

    expect(result.ok).toBe(true)
    if (!result.ok) {
      continue
    }

    expect(result.source).toContain(`_catalogColumn<unknown, unknown, unknown, ${sqlDomain}>()`)
  }
})

test("returns diagnostics without source for lossy input and name collisions", () => {
  const lossy = generateSchemaSource({
    ...codegenInput,
    lossy: true,
  })

  expect(lossy.ok).toBe(false)
  expect(lossy).not.toHaveProperty("source")
  if (!lossy.ok) {
    expect(lossy.diagnostics).toEqual(
      expect.arrayContaining([expect.objectContaining({ code: "lossy-input" })]),
    )
  }

  const collision = generateSchemaSource(codegenInput, {
    naming(context) {
      if (context.kind === "table") {
        return "records"
      }
    },
  })

  expect(collision.ok).toBe(false)
  expect(collision).not.toHaveProperty("source")
  if (!collision.ok) {
    expect(collision.diagnostics).toEqual(
      expect.arrayContaining([expect.objectContaining({ code: "name-collision" })]),
    )
  }

  const unsafe = generateSchemaSource(codegenInput, {
    naming(context) {
      if (context.kind === "table") {
        return "not-source-safe"
      }
    },
  })

  expect(unsafe.ok).toBe(false)
  expect(unsafe).not.toHaveProperty("source")
  if (!unsafe.ok) {
    expect(unsafe.diagnostics).toEqual(
      expect.arrayContaining([expect.objectContaining({ code: "unsafe-name" })]),
    )
  }
})

test("rejects strict-mode reserved export bindings from defaults and callbacks", () => {
  const strictBindings = [
    "arguments",
    "eval",
    "implements",
    "interface",
    "package",
    "private",
    "protected",
    "public",
  ] as const

  for (const binding of strictBindings) {
    const fromDefault = generateSchemaSource(nativeTypeInput("postgresql", "integer", binding))

    expect(fromDefault.ok).toBe(false)
    expect(fromDefault).not.toHaveProperty("source")
    if (!fromDefault.ok) {
      expect(fromDefault.diagnostics).toEqual(
        expect.arrayContaining([expect.objectContaining({ code: "unsafe-name" })]),
      )
    }

    const fromCallback = generateSchemaSource(nativeTypeInput("postgresql", "integer"), {
      naming(context) {
        return context.kind === "table" ? binding : undefined
      },
    })

    expect(fromCallback.ok).toBe(false)
    expect(fromCallback).not.toHaveProperty("source")
    if (!fromCallback.ok) {
      expect(fromCallback.diagnostics).toEqual(
        expect.arrayContaining([expect.objectContaining({ code: "unsafe-name" })]),
      )
    }
  }
})

